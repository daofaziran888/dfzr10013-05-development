def _days(start: str, end: str) -> list[str]:
    current = date.fromisoformat(start)
    stop = date.fromisoformat(end)
    rows: list[str] = []
    while current <= stop:
        rows.append(current.isoformat())
        current += timedelta(days=1)
    return rows


