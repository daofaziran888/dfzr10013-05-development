OUTPUTS: list[dict[str, Any]] = []


def _daily_output(department: str, quantity: float, unit: str, start: str = "2026-06-01", end: str = "2026-06-30") -> None:
    for day in _days(start, end):
        OUTPUTS.append({
            "部门": department,
            "日期": day,
            "数量": quantity,
            "单位": unit,
            "上报时间": "2026-07-01T10:00:00",
            "上报类型": "正常",
        })


_daily_output("销售一部", 20.0, "件")
_daily_output("销售二部", 15.0, "件")
_daily_output("交付中心", 12.0, "件")
_daily_output("客服部", 10.0, "单")
